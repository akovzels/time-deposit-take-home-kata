-- XA Bank time deposit schema. Table and column names follow the root README;
-- camel-case identifiers are quoted so PostgreSQL preserves them exactly.
-- planType is deliberately NOT constrained to the currently known plans.

CREATE TABLE "timeDeposits" (
    id         integer       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "planType" varchar(255)  NOT NULL,
    days       integer       NOT NULL,
    balance    numeric(19,2) NOT NULL
);

CREATE TABLE withdrawals (
    id              integer       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "timeDepositId" integer       NOT NULL REFERENCES "timeDeposits" (id),
    amount          numeric(19,2) NOT NULL,
    date            date          NOT NULL
);

CREATE INDEX withdrawals_timeDepositId_idx ON withdrawals ("timeDepositId");
